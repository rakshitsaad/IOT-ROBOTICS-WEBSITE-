const SHAPES = { L: [1500, 1000], W: [1600, 900], P: [1000, 1500], F: [1200, 1500], S: [1200, 1200] } as const;

/** A project's gallery: one placeholder photo per letter of `shapes`. */
function gallery(seed: string, title: string, shapes: string): ProjectImage[] {
  return [...shapes].map((shape, i) => {
    const [width, height] = SHAPES[shape as keyof typeof SHAPES];
    return {
      url: `https://picsum.photos/seed/iotr-${seed}-${i + 1}/${width}/${height}`,
      width,
      height,
      alt: `${title}, photo ${i + 1} of ${shapes.length}`,
    };
  });
}

